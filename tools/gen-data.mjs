// Writes src/data/all.js importing whatever content files exist (agents add them independently).
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const d = (p) => path.join(root, 'src/data', p);
const list = (dir) => (fs.existsSync(d(dir)) ? fs.readdirSync(d(dir)).filter((f) => f.endsWith('.js')).sort() : []);
const qs = list('q');
const ws = list('written');
const ORDER = ['practice-2019', 'test1-2025', 'mock-2019', 'test1-2024'];
const ps = list('papers').sort((a, b) => (ORDER.indexOf(a.replace('.js', '')) + 99) % 99 - (ORDER.indexOf(b.replace('.js', '')) + 99) % 99);
const cheatFile = process.env.TEST_CHEAT ? 'cheat/_test_blocks.js' : 'cheat/blocks.js';
const hasCheat = fs.existsSync(d(cheatFile));
let out = '// GENERATED by tools/gen-data.mjs — do not edit.\n';
qs.forEach((f, i) => (out += `import q${i} from './q/${f}';\n`));
ws.forEach((f, i) => (out += `import w${i} from './written/${f}';\n`));
ps.forEach((f, i) => (out += `import p${i} from './papers/${f}';\n`));
if (hasCheat) out += `import cheat from './${cheatFile}';\n`;
out += `export const QUESTIONS = [${qs.map((_, i) => `...q${i}`).join(', ')}];\n`;
out += `export const WRITTEN = [${ws.map((_, i) => `...w${i}`).join(', ')}];\n`;
out += `export const PAPERS = [${ps.map((_, i) => `p${i}`).join(', ')}];\n`;
out += `export const CHEAT = ${hasCheat ? 'cheat' : '[]'};\n`;
fs.writeFileSync(d('all.js'), out);
console.log(`data: ${qs.length} MCQ files, ${ws.length} written files, ${ps.length} papers, cheat ${hasCheat ? 'yes' : 'no'}`);
